-- Multi-tenant, migration 3: project teams with roles, types of work,
-- and "same company" protections.
--
-- Still the "expand" phase: project_assignments stays in place and the
-- live app keeps using it. project_members is filled from it once, here;
-- the backend switch moves the app over to project_members.
