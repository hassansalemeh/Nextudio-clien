-- =====================================================================
-- Finance: money locations, suppliers, categories, agreements,
-- and a single money_movements table for every money in / out / transfer.
--
-- Assumes the legacy `transactions` table has already been dropped.
-- `invoice_disbursements` is NOT dropped here: switch the invoice pages
-- to money_movements first, then drop it in a follow-up migration.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. Money locations: where money physically sits
--    Nextudio's own places (bank, safe, Whish...) have no project.
--    Each project has exactly one site fund.
-- ---------------------------------------------------------------------
create table money_locations (
  id          bigint generated by default as identity primary key,
  name        text        not null,
  kind        text        not null check (kind in ('bank', 'cash', 'wallet', 'site_fund')),
  currency    text        not null default 'USD',
  project_id  bigint      references projects(id) on delete restrict,
  is_active   boolean     not null default true,
  created_at  timestamptz not null default now(),

  -- a site fund always belongs to a project; Nextudio's own places never do
  constraint site_fund_has_project check (
    (kind = 'site_fund' and project_id is not null)
    or (kind <> 'site_fund' and project_id is null)
  )
);

-- one site fund per project
create unique index money_locations_one_site_fund_per_project
  on money_locations (project_id) where kind = 'site_fund';


-- ---------------------------------------------------------------------
-- 2. Suppliers and site workers (people who are not clients or employees)
-- ---------------------------------------------------------------------
create table suppliers (
  id          bigint generated by default as identity primary key,
  name        text        not null,
  phone       text,
  trade       text,                 -- e.g. 'Steel', 'Concrete', 'Masonry'
  notes       text,
  is_active   boolean     not null default true,
  created_at  timestamptz not null default now()
);

-- stops "Mamdouh" and "mamdouh " from becoming two people
create unique index suppliers_unique_name on suppliers (lower(trim(name)));


-- ---------------------------------------------------------------------
